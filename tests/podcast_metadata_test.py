import xml.etree.ElementTree as ET
import itertools
import os
from pathlib import Path
import subprocess
from urllib.parse import quote

KEYS=('YENEY_PODCAST_TITLE_PLAIN','YENEY_PODCAST_ARTIST_SHOW','YENEY_PODCAST_ALBUM_PUBLISHER')

def native_matrix(cli,mac,origin,base,root):
    subprocess.run(["make","podcast-metadata-fixture"],cwd=root,check=True)
    for name in ('Generated from Coast','Generated by Writer','Suffix Show | Plus','Plain'):
        cli('podcasts addshow '+quote(origin+'/feed.xml?'+quote(name),safe='')+' '+quote(name,safe=''),mac)
        menu=cli('podcasts items 0 100 want_url:1',mac)
        ident=menu[menu.index('name:'+name)-1].split(':',1)[1]
        cli('podcasts items 0 100 want_url:1 item_id:'+ident,mac)
        podcast=name.split(' | ')[0]
        publisher='Fixture by Author' if name=='Plain' else 'Fixture Author'
        formatted='Episode 3 by '+publisher+' from '+podcast
        for bits in itertools.product(('no','yes'),repeat=3):
            env={k:v for k,v in os.environ.items() if k not in KEYS}
            env.update(zip(KEYS,bits))
            result=subprocess.check_output([str(root/'podcast-metadata-fixture'),'127.0.0.1',mac,formatted,str(base/'no-config')],env=env)
            didl=result.split(b'<DIDL-Lite',1)[1]
            item=ET.fromstring(b'<DIDL-Lite'+didl)[0]
            assert [n.tag.rsplit('}',1)[-1] for n in item][:4]==['title','creator','artist','album']
            fixture=root/'tests/fixtures'/('podcast-'+({'Generated from Coast':'from','Generated by Writer':'by','Suffix Show | Plus':'plus','Plain':'plain'}[name])+'-'+''.join('1' if v=='yes' else '0' for v in bits)+'.xml')
            assert b'<DIDL-Lite'+didl==fixture.read_bytes(),(name,bits,result)
        print('PASS native LMS 9.1.1 podcast metadata: '+name+'; all eight settings, byte-exact DIDL wire fixtures, direct binary without systemd',flush=True)

def settings_test():
    import tempfile
    root=Path(__file__).resolve().parents[1]
    with tempfile.TemporaryDirectory(prefix='podcast-settings-',dir=os.environ.get('TMPDIR','/var/tmp')) as directory:
        config=Path(directory)/'config'
        clean={k:v for k,v in os.environ.items() if k not in KEYS}
        def check(lines,overrides,values,sources,invalid=0):
            config.write_text(lines)
            output=subprocess.check_output([str(root/'podcast-metadata-fixture'),'settings','unused','unused',str(config)],env={**clean,**overrides},text=True)
            for k,v,source in zip(KEYS,values,sources):assert f'{k}={v} source={source}' in output,output
            assert output.count('invalid ')==invalid,output
        defaults=('yes','yes','no')
        check('',{},defaults,['default']*3)
        global_config=''.join(k+'=no\n' for k in KEYS)
        room_config=''.join('room.Study.'+k+'=yes\n' for k in KEYS)
        check(global_config,{},['no']*3,['global-config']*3)
        check(global_config+room_config,{},['yes']*3,['room-config']*3)
        check(global_config+room_config,dict.fromkeys(KEYS,'no'),['no']*3,['environment']*3)
        check(global_config+room_config,dict.fromkeys(KEYS,'invalid'),defaults,['environment']*3,3)
        check(''.join(k+'=invalid\n' for k in KEYS),{},defaults,['global-config']*3,3)
        check(''.join('room.Study.'+k+'=invalid\n' for k in KEYS),{},defaults,['room-config']*3,3)
    print('PASS podcast settings: defaults, global, room, environment precedence; invalid values warn once and use defaults; direct binary without systemd',flush=True)

def lookup_test():
    import socketserver
    import threading
    import time
    root=Path(__file__).resolve().parents[1]
    scenario={'kind':'owner','commands':[]}
    class Handler(socketserver.StreamRequestHandler):
        def handle(self):
            line=self.rfile.readline().decode().strip()
            mac,command=line.split(' ',1)
            assert command.startswith('podcasts items '),command
            scenario['commands'].append(command)
            kind=scenario['kind']
            if kind=='timeout':
                time.sleep(2.1)
                return
            if 'item_id:' not in command:
                fields=[] if kind=='no-feed' else ['id:4','name:Boekestijn & De Wijk | Plus','url:fixture','id:5','name:Amerika in 15 minuten','url:fixture','count:2']
            elif 'item_id:4' in command:
                fields=['id:4.0','title:Lavrov dreigt met verdere escalatie','count:'+('1' if kind=='no-episode' else '1703')]
            else:
                fields=['id:5.0','title:'+('Other episode' if kind=='no-episode' else 'Trump vestigt zijn hoop op het linkse Maine'),'count:1']
            self.wfile.write((line+' '+ ' '.join(quote(f,safe='') for f in fields)+'\n').encode())
    class Server(socketserver.ThreadingTCPServer):
        allow_reuse_address=True
        daemon_threads=True
    with Server(('127.0.0.1',9090),Handler) as server:
        thread=threading.Thread(target=server.serve_forever);thread.start()
        try:
            for kind in ('owner','no-feed','no-episode','timeout'):
                scenario.update(kind=kind,commands=[])
                title='Trump vestigt zijn hoop op het linkse Maine'
                start=time.monotonic()
                result=subprocess.run([str(root/'podcast-metadata-fixture'),'127.0.0.1','02:00:00:00:00:01',title,'/nonexistent'],capture_output=True,text=True)
                elapsed=time.monotonic()-start
                if kind=='owner':
                    assert result.returncode==0 and 'Amerika in 15 minuten' in result.stdout,(result.stdout,result.stderr)
                    assert not any('items 100 ' in c for c in scenario['commands']),scenario
                else:
                    assert result.returncode==1,result
                    expected={'no-feed':'no feed match','no-episode':'no episode match','timeout':'lookup timeout'}[kind]
                    assert expected in result.stderr,result.stderr
                assert elapsed<2.5,elapsed
                print(f'PASS podcast lookup {kind}: {elapsed:.3f}s, '+(result.stderr.strip() or 'owner plain title matched before unrelated older pages'),flush=True)
        finally:
            server.shutdown();thread.join()

if __name__=='__main__':
    settings_test()
    lookup_test()
