import itertools
import os
from pathlib import Path
import subprocess
from urllib.parse import quote

KEYS=('YENEY_PODCAST_TITLE_PLAIN','YENEY_PODCAST_ARTIST_SHOW','YENEY_PODCAST_ALBUM_PUBLISHER')

def native_matrix(cli,mac,origin,base,root):
    subprocess.run(["make","podcast-metadata-fixture"],cwd=root,check=True)
    for name in ('Generated from Coast','Generated by Writer'):
        cli('podcasts addshow '+quote(origin+'/feed.xml?'+quote(name),safe='')+' '+quote(name,safe=''),mac)
        menu=cli('podcasts items 0 100 want_url:1',mac)
        ident=menu[menu.index('name:'+name)-1].split(':',1)[1]
        cli('podcasts items 0 100 want_url:1 item_id:'+ident,mac)
        formatted='Episode 3 by Fixture Author from '+name
        for bits in itertools.product(('no','yes'),repeat=3):
            env={k:v for k,v in os.environ.items() if k not in KEYS}
            env.update(zip(KEYS,bits))
            result=subprocess.check_output([str(root/'podcast-metadata-fixture'),'127.0.0.1',mac,formatted,str(base/'no-config')],env=env)
            didl=result.split(b'<DIDL-Lite',1)[1]
            fixture=root/'tests/fixtures'/('podcast-'+('from' if ' from ' in name else 'by')+'-'+''.join('1' if v=='yes' else '0' for v in bits)+'.xml')
            assert b'<DIDL-Lite'+didl==fixture.read_bytes(),(name,bits,result)
        print('PASS native LMS 9.1.1 podcast metadata: '+name+'; all eight settings, byte-exact DIDL wire fixtures, direct binary without systemd',flush=True)

def settings_test():
    import tempfile
    root=Path(__file__).resolve().parents[1]
    with tempfile.TemporaryDirectory(prefix='podcast-settings-',dir=os.environ.get('TMPDIR','/var/tmp')) as directory:
        config=Path(directory)/'config'
        clean={k:v for k,v in os.environ.items() if k not in KEYS}
        def check(lines,overrides,values,sources,invalid=0):
            config.write_text(lines)
            output=subprocess.check_output([str(root/'podcast-metadata-fixture'),'settings','unused','unused',str(config)],env={**clean,**overrides},text=True)
            for k,v,source in zip(KEYS,values,sources):assert f'{k}={v} source={source}' in output,output
            assert output.count('invalid ')==invalid,output
        defaults=('yes','yes','no')
        check('',{},defaults,['default']*3)
        global_config=''.join(k+'=no\n' for k in KEYS)
        room_config=''.join('room.Study.'+k+'=yes\n' for k in KEYS)
        check(global_config,{},['no']*3,['global-config']*3)
        check(global_config+room_config,{},['yes']*3,['room-config']*3)
        check(global_config+room_config,dict.fromkeys(KEYS,'no'),['no']*3,['environment']*3)
        check(global_config+room_config,dict.fromkeys(KEYS,'invalid'),defaults,['environment']*3,3)
        check(''.join(k+'=invalid\n' for k in KEYS),{},defaults,['global-config']*3,3)
        check(''.join('room.Study.'+k+'=invalid\n' for k in KEYS),{},defaults,['room-config']*3,3)
    print('PASS podcast settings: defaults, global, room, environment precedence; invalid values warn once and use defaults; direct binary without systemd',flush=True)

if __name__=='__main__':settings_test()
