#!/usr/bin/env python3
"""Generate compile-time bridge identity; update only when revisions change."""
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
def revision(path):
    return subprocess.check_output(['git', '-C', str(path), 'rev-parse', '--short=7', 'HEAD'], text=True).strip()

release = (ROOT / 'VERSION').read_text().strip()
version = f'{release}-{revision(ROOT)} (core {revision(ROOT / "third_party/yeney-core")})'
target = ROOT / 'bridge_version.h'
text = ('// Generated by scripts/build-version.py.\n#pragma once\n'
        'namespace bridge { inline const char *firmwareVersion() { return '
        + json.dumps(version) + '; } }\n')
if not target.exists() or target.read_text() != text:
    target.write_text(text)
